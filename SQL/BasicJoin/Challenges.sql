WITH CHALLENGES_COUNT AS (
    SELECT 
        H.HACKER_ID, H.NAME, 
        COUNT(CHALLENGE_ID) AS TOTAL_CREATE
    FROM HACKERS H
    JOIN CHALLENGES C ON H.HACKER_ID = C.HACKER_ID
    GROUP BY H.HACKER_ID, H.NAME
)

SELECT HACKER_ID, NAME, TOTAL_CREATE 
FROM CHALLENGES_COUNT
WHERE TOTAL_CREATE = (
    SELECT MAX(TOTAL_CREATE) FROM CHALLENGES_COUNT
) OR TOTAL_CREATE IN (
    SELECT TOTAL_CREATE FROM CHALLENGES_COUNT
    GROUP BY TOTAL_CREATE
    HAVING COUNT(TOTAL_CREATE) = 1
)
ORDER BY TOTAL_CREATE DESC, HACKER_ID;
