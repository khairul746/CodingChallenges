WITH SUM_VIEWS AS (
    SELECT 
        CTS.CONTEST_ID, HACKER_ID, NAME,
        SUM(TOTAL_VIEWS) AS SUM_TOT_VIEWS, 
        SUM(TOTAL_UNIQUE_VIEWS) AS SUM_TOT_UNIQUE_VIEWS
    FROM CONTESTS CTS
    JOIN COLLEGES CLG ON CLG.CONTEST_ID = CTS.CONTEST_ID
    JOIN CHALLENGES CHL ON CHL.COLLEGE_ID = CLG.COLLEGE_ID
    JOIN VIEW_STATS VST ON VST.CHALLENGE_ID = CHL.CHALLENGE_ID
    GROUP BY CTS.CONTEST_ID, HACKER_ID, NAME
), SUM_SUBMISSIONS AS (
    SELECT 
        CTS.CONTEST_ID, HACKER_ID, NAME,
        SUM(TOTAL_SUBMISSIONS) AS SUM_TOT_SUBMISSIONS, 
        SUM(TOTAL_ACCEPTED_SUBMISSIONS) AS SUM_TOT_ACC_SUBMISSIONS
    FROM CONTESTS CTS
    JOIN COLLEGES CLG ON CLG.CONTEST_ID = CTS.CONTEST_ID
    JOIN CHALLENGES CHL ON CHL.COLLEGE_ID = CLG.COLLEGE_ID
    JOIN SUBMISSION_STATS SST ON SST.CHALLENGE_ID = CHL.CHALLENGE_ID
    GROUP BY CTS.CONTEST_ID, HACKER_ID, NAME
)
SELECT
    SS.CONTEST_ID, SS.HACKER_ID, SS.NAME,
    SUM_TOT_SUBMISSIONS, SUM_TOT_ACC_SUBMISSIONS,
    SUM_TOT_VIEWS, SUM_TOT_UNIQUE_VIEWS
FROM SUM_SUBMISSIONS SS
JOIN SUM_VIEWS SV ON SV.CONTEST_ID = SS.CONTEST_ID
ORDER BY SS.CONTEST_ID;
