WITH PROJECT_STARTS AS (
    SELECT START_DATE, ROW_NUMBER() OVER (ORDER BY START_DATE) AS RN
    FROM PROJECTS
    WHERE START_DATE NOT IN (SELECT END_DATE FROM PROJECTS)
), PROJECT_ENDS AS (
    SELECT END_DATE, ROW_NUMBER() OVER (ORDER BY END_DATE) AS RN
    FROM PROJECTS
    WHERE END_DATE NOT IN (SELECT START_DATE FROM PROJECTS)
)
SELECT PS.START_DATE, PE.END_DATE
FROM PROJECT_STARTS PS
JOIN PROJECT_ENDS PE ON PS.RN = PE.RN
ORDER BY DATEDIFF(PE.END_DATE, PS.START_DATE) ASC, PS.START_DATE ASC;
