WITH UNIQUE_HACKERS_PER_DAY AS (
    SELECT DISTINCT SUBMISSION_DATE, HACKER_ID
    FROM SUBMISSIONS
),
CONTINUOUS_HACKERS AS (
    SELECT 
        S1.SUBMISSION_DATE,
        S1.HACKER_ID,
        (
            SELECT COUNT(DISTINCT S2.SUBMISSION_DATE) 
            FROM SUBMISSIONS S2 
            WHERE S2.HACKER_ID = S1.HACKER_ID 
              AND S2.SUBMISSION_DATE <= S1.SUBMISSION_DATE
        ) AS ACTIVE_DAYS,
        (
            SELECT COUNT(DISTINCT S3.SUBMISSION_DATE) 
            FROM SUBMISSIONS S3 
            WHERE S3.SUBMISSION_DATE <= S1.SUBMISSION_DATE
        ) AS TOTAL_ELAPSED_DAYS
    FROM UNIQUE_HACKERS_PER_DAY S1
),
VALID_CONTINUOUS_HACKERS AS (
    SELECT SUBMISSION_DATE, COUNT(DISTINCT HACKER_ID) AS TOTAL_CONSISTENT_HACKERS
    FROM CONTINUOUS_HACKERS
    WHERE ACTIVE_DAYS = TOTAL_ELAPSED_DAYS
    GROUP BY SUBMISSION_DATE
),
DAILY_SUBMISSIONS_COUNT AS (
    SELECT SUBMISSION_DATE, HACKER_ID, COUNT(*) AS NUM_SUBS
    FROM SUBMISSIONS
    GROUP BY SUBMISSION_DATE, HACKER_ID
),
RANKED_DAILY_HACKERS AS (
    SELECT 
        D.SUBMISSION_DATE,
        D.HACKER_ID,
        H.NAME,
        DENSE_RANK() OVER(
            PARTITION BY D.SUBMISSION_DATE 
            ORDER BY D.NUM_SUBS DESC, D.HACKER_ID ASC
        ) AS RN
    FROM DAILY_SUBMISSIONS_COUNT D
    JOIN HACKERS H ON D.HACKER_ID = H.HACKER_ID
),
TOP_HACKER_PER_DAY AS (
    SELECT SUBMISSION_DATE, HACKER_ID, NAME
    FROM RANKED_DAILY_HACKERS
    WHERE RN = 1
)
SELECT 
    V.SUBMISSION_DATE,
    V.TOTAL_CONSISTENT_HACKERS,
    T.HACKER_ID,
    T.NAME
FROM VALID_CONTINUOUS_HACKERS V
JOIN TOP_HACKER_PER_DAY T ON V.SUBMISSION_DATE = T.SUBMISSION_DATE
ORDER BY V.SUBMISSION_DATE ASC;
